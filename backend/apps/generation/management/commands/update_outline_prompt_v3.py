# backend/apps/generation/management/commands/update_outline_prompt_v3.py
"""更新大纲生成提示词模板 V3 - 使用用户提供的精确版本。"""

from django.core.management.base import BaseCommand
from django.db import transaction

from apps.generation.constants import PromptVersionStatus
from apps.generation.models import PromptTemplate, PromptVersion


class Command(BaseCommand):
    help = "更新大纲生成提示词模板 V3"

    @transaction.atomic
    def handle(self, *args, **options):
        template = PromptTemplate.objects.filter(scenario='outline_generation').first()
        if not template:
            self.stdout.write(self.style.ERROR("未找到 outline_generation 模板"))
            return

        # 用户提供的精确提示词（一字不改）
        system_prompt = '''你是一名资深投标文件编制专家，请从我上传的招标文件、采购文件、磋商文件、比选文件、询价文件或其他采购类文件中，提取"投标文件/响应文件最终成册目录"。

请注意：我要的不是招标文件自身目录，也不是简单提取 Word 标题，而是站在投标人编制投标文件的角度，整理出最终提交文件中应该出现的多级目录。

请先通读全文，自动识别与投标文件编制有关的所有依据，包括但不限于："投标文件组成、响应文件组成、参选文件组成、报价文件组成、申请文件组成、文件编制顺序、投标文件格式、响应文件格式、附件格式、资格证明文件、商务文件、技术文件、报价文件、资格审查、符合性审查、初步评审、详细评审、商务评审、技术评审、价格评审、评分标准、否决项、实质性要求、承诺函、声明函、偏离表、应答表、报价表、证明材料、人员材料、案例材料、财务材料、资质证书、截图、合同复印件、盖章、签字、原件备查"等内容。

请按照以下原则整理目录：优先采用文件中明确规定的"投标文件/响应文件组成或编制顺序"作为主目录顺序；再结合"投标文件格式/响应文件格式/附件模板"补充具体表格、承诺函、声明函、偏离表、报价表等内容；再结合资格审查、符合性审查、初步评审、详细评分标准补充必须提交或建议提交的支撑材料；最后结合全文中所有"须提供、应提供、必须提供、需提供、加盖公章、签字、否则否决、不满足将被否决、实质性响应"等要求，检查是否还有遗漏材料。

目录层级请按正式投标文件逻辑组织，不要机械照搬招标文件章节。一般情况下，投标函、授权文件、资格证明文件、商务响应文件、技术响应文件、报价文件、偏离表、承诺函、其他材料等可作为一级目录；一级目录下的具体表格、证明文件、承诺函、人员材料、案例材料、技术方案小节等作为二级或三级目录。对于"资格证明文件"，应结合资格条件和资格审查要求展开，例如营业执照、法人证明、授权委托、资质证书、财务状况、纳税社保、类似业绩、信用记录、无重大违法违规声明、非联合体声明、不分包转包承诺等。对于"技术文件/技术方案"，应结合技术需求和技术评分项展开，例如项目理解、需求分析、总体方案、实施方案、项目组织、人员团队、进度计划、质量保障、风险控制、售后服务、培训方案、应急响应、交付成果、安全保障、同类经验等。对于"商务文件"，应结合商务条款、合同条款、服务期限、付款条件、商务偏离表、服务承诺等展开。对于"报价文件"，应结合开标一览表、报价表、分项报价表、价格明细表、税率说明、报价说明等展开。

请保留招标文件中明确要求的原始编号和名称；如原文没有编号，可按照正式投标文件目录规则补充编号。推荐编号格式为：一级目录使用"一、二、三、四"；二级目录使用"（一）（二）（三）"；三级目录使用"1、2、3"；四级目录使用"1.1、1.2、1.3"；五级目录使用"（1）（2）（3）"。遇到跨页、跨行、断开的标题，请自动合并为完整标题。遇到标题过长的承诺函或证明材料，可在不改变含义的前提下压缩为适合目录使用的标题。

请清理页眉、页脚、页码、目录点线、重复标题、模板说明、纯解释性正文、管理性正文、法律性长条款。不要把招标文件自身目录、合同正文、技术需求正文、评分细则全文、评审办法正文整段误当作投标目录。评分细则中只提取需要放入投标文件的支撑材料或可作为技术方案章节的内容。对于同义重复内容应合并，例如"授权委托书"和"法定代表人授权委托书"如含义一致，应合并；"类似项目案例"和"同类业绩证明"如指向相同材料，应合并。对于招标文件明确要求提交的内容，必须保留；对于根据评分标准或投标完整性建议补充的内容，可以保留，但必须标注为"建议补充"，不要混同为强制要求。

请在正式输出前进行三轮自检，但不要展示自检过程：

第一轮，检查是否遗漏"投标文件组成/响应文件组成/编制顺序"中明确列出的一级目录和关键材料；

第二轮，检查是否遗漏"投标文件格式/响应文件格式/附件模板"中的表格、承诺函、声明函、偏离表、报价表、索引表等；

第三轮，检查是否遗漏资格审查、符合性审查、商务评审、技术评审、报价评审、否决项、实质性要求中要求提交的证明材料，并检查是否存在层级错误、编号混乱、重复标题、把招标文件正文误提取为投标目录的问题。

最终只输出自检修正后的结果，按以下格式输出：

第一部分：最终投标文件多级目录

要求输出一版可以直接复制到 Word 中使用的多级目录，目录名称要正式、简洁、清晰，层级要合理。

第二部分：来源依据与编制提示表

请用表格列出：

| 序号 | 目录名称 | 层级 | 来源依据 | 要求类型 | 编制提示 |
|---|---|---|---|---|---|

字段说明：
1. 序号：与最终目录对应；
2. 目录名称：对应最终目录中的标题；
3. 层级：一级、二级、三级、四级；
4. 来源依据：说明来自投标文件组成、响应文件格式、资格审查、符合性审查、商务评分、技术评分、报价要求、合同条款响应、否决项、实质性要求或其他要求，不要强行写死章节号；如果文件中有明确章节号，可以同时注明；
5. 要求类型：标注为"明确要求""格式要求"或"建议补充"；
6. 编制提示：简要说明该目录下应放什么材料，是否需要盖章、签字、截图、证书、合同复印件、审计报告、社保证明、纳税证明、承诺函、偏离说明、原件备查等。

输出时请先给"最终投标文件多级目录"，再给"来源依据与编制提示表"。不要输出思考过程，不要解释抽取规则，不要反复说明方法，直接给出整理好的结果。'''

        user_prompt = '''请从以下招标文件全文中提取投标文件/响应文件最终成册目录：

**项目名称**：{{ project_name }}

**招标文件全文内容**：
{{ tender_document_full_text }}'''

        # 创建新版本（version 3.0）
        existing_versions = PromptVersion.objects.filter(template=template)
        for v in existing_versions:
            v.status = PromptVersionStatus.ARCHIVED
            v.save()

        version = PromptVersion.objects.create(
            template=template,
            version='3.0',
            system_prompt=system_prompt,
            user_prompt=user_prompt,
            changelog='使用用户提供的精确提示词，传入完整招标文件内容',
            status=PromptVersionStatus.PUBLISHED,
        )

        self.stdout.write(self.style.SUCCESS(f"已创建并发布版本 3.0 (ID={version.id})"))

        # 验证
        published = PromptVersion.objects.filter(template=template, status='published').first()
        self.stdout.write(f"当前发布版本: {published.version} (ID={published.id})")